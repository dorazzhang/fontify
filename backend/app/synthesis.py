def synthesize_mask(
    ch: str,
    *,
    width: int = 360,
    height: int = 300,
    stroke_px: float = 6.0,
    target_height_px: float = 120.0,
    baseline_from_top: float = 0.74,
) -> np.ndarray:
    """
    Rasterize a simple skeleton for a missing character.

    The ink is scaled to ``target_height_px`` and seated on the same baseline
    fraction used for live captures so size matches written glyphs.
    """
    # Draw oversized, then uniformly scale to the corpus height target
    pad = 40
    work_h, work_w = 400, 400
    canvas = np.zeros((work_h, work_w), dtype=np.uint8)
    thickness = max(2, int(round(stroke_px * (work_h / max(height, 1)))))
    key = ch
    paths = _SKEL.get(key)
    if not paths:
        _stroke_circle(canvas, (0.5, 0.55), 0.18, thickness)
    else:
        for poly in paths:
            if len(poly) == 1:
                _stroke_circle(canvas, poly[0], 0.04, thickness)
            else:
                _stroke_polyline(canvas, poly, thickness, closed=False)

    blur = cv2.GaussianBlur(canvas, (3, 3), 0)
    _, ink = cv2.threshold(blur, 40, 255, cv2.THRESH_BINARY)

    ys, xs = np.where(ink > 0)
    out = np.zeros((height, width), dtype=np.uint8)
    if len(xs) == 0:
        return out

    x0, x1 = int(xs.min()), int(xs.max())
    y0, y1 = int(ys.min()), int(ys.max())
    crop = ink[y0 : y1 + 1, x0 : x1 + 1]
    ch_h = max(y1 - y0 + 1, 1)
    ch_w = max(x1 - x0 + 1, 1)

    # Lowercase targets ~70% of cap height; punctuation smaller
    height_mul = 1.0
    if ch.islower():
        height_mul = 0.70
        if ch in set("bdfhiklt"):
            height_mul = 0.95
        if ch in set("gjpqy"):
            height_mul = 0.95
    elif ch in set(".,;:'\""):
        height_mul = 0.22
    elif ch in set("-"):
        height_mul = 0.18
    elif ch.isdigit():
        height_mul = 0.92

    dest_h = max(int(round(target_height_px * height_mul)), 8)
    dest_w = max(int(round(ch_w * (dest_h / ch_h))), 4)
    dest_w = min(dest_w, width - 2 * pad)
    dest_h = min(dest_h, height - 2 * pad)
    resized = cv2.resize(crop, (dest_w, dest_h), interpolation=cv2.INTER_AREA)
    _, resized = cv2.threshold(resized, 40, 255, cv2.THRESH_BINARY)

    baseline = int(round(baseline_from_top * height))
    # Sit glyph so its geometric baseline band lands near the live baseline.
    # For most letters, bottom of ink ≈ baseline (descenders extend past).
    if ch in set("gjpqy,;"):
        top = baseline - int(round(dest_h * 0.72))
    elif ch in set(".,"):
        top = baseline - dest_h
    else:
        top = baseline - dest_h
    left = (width - dest_w) // 2
    top = int(np.clip(top, 0, height - dest_h))
    left = int(np.clip(left, 0, width - dest_w))
    out[top : top + dest_h, left : left + dest_w] = np.maximum(
        out[top : top + dest_h, left : left + dest_w],
        resized,
    )
    return out
