"""Synthesize missing glyphs so the face never falls back to another font."""

from __future__ import annotations

import cv2
import numpy as np

# Characters we always try to ship in a live font
CORE_CHARSET = (
    "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    "abcdefghijklmnopqrstuvwxyz"
    "0123456789"
    "!?#$&@.,;:'\"-()"
)


def _stroke_polyline(
    canvas: np.ndarray,
    points: list[tuple[float, float]],
    thickness: int,
    closed: bool = False,
) -> None:
    if len(points) < 2:
        return
    h, w = canvas.shape
    pts = np.array(
        [[int(round(x * (w - 1))), int(round(y * (h - 1)))] for x, y in points],
        dtype=np.int32,
    )
    cv2.polylines(
        canvas,
        [pts],
        isClosed=closed,
        color=255,
        thickness=max(1, thickness),
        lineType=cv2.LINE_AA,
    )


def _stroke_circle(
    canvas: np.ndarray,
    center: tuple[float, float],
    radius: float,
    thickness: int,
) -> None:
    h, w = canvas.shape
    cv2.circle(
        canvas,
        (int(round(center[0] * (w - 1))), int(round(center[1] * (h - 1)))),
        max(1, int(round(radius * min(h, w)))),
        255,
        thickness=max(1, thickness),
        lineType=cv2.LINE_AA,
    )


